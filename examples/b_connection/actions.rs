//! Entries and exits, as generated linear code (spec 5.3 steps 1, 7).
//!
//! The user writes the per-state functions (`entry_*`, `exit_*`); the macro
//! writes the composites that walk the hierarchy: the deepest state exits
//! first, regions in reverse declaration order, the parallel state last; on
//! entry the parallel state comes first, then the regions in declaration
//! order. Every action logs a line in the global context, so tests can assert
//! the exact order of entries, exits, handlers and effects.

use estado_core::{Cx, Sink};

use super::model::{Command, Conn, Event, Keepalive, Link};
use super::tasks::{cancel_root, start_root};
use super::views::{BackoffMut, ConnectedFields, ConnectingMut, SendingMut};

/// The `Cx` of this machine.
pub type ConnCx<'step, S> = Cx<'step, Conn, S>;

/// Appends a line to the trace kept in the global context.
pub fn note<S: Sink<Command>>(cx: &mut ConnCx<'_, S>, line: &str) {
    cx.ctx_mut().push(line.to_owned());
}

/// Traces and emits a command.
pub fn emit<S: Sink<Command>>(cx: &mut ConnCx<'_, S>, command: Command) {
    let line = format!("emit {command:?}");
    cx.ctx_mut().push(line);
    cx.emit(command);
}

// Entries and exits written by the user, one per state.

fn entry_disconnected<S: Sink<Command>>(cx: &mut ConnCx<'_, S>) {
    note(cx, "entry Disconnected");
}

fn exit_disconnected<S: Sink<Command>>(cx: &mut ConnCx<'_, S>) {
    note(cx, "exit Disconnected");
}

fn entry_connecting<S: Sink<Command>>(_connecting: ConnectingMut<'_>, cx: &mut ConnCx<'_, S>) {
    note(cx, "entry Connecting");
}

fn exit_connecting<S: Sink<Command>>(_connecting: ConnectingMut<'_>, cx: &mut ConnCx<'_, S>) {
    note(cx, "exit Connecting");
}

fn entry_backoff<S: Sink<Command>>(_backoff: BackoffMut<'_>, cx: &mut ConnCx<'_, S>) {
    note(cx, "entry Backoff");
}

fn exit_backoff<S: Sink<Command>>(_backoff: BackoffMut<'_>, cx: &mut ConnCx<'_, S>) {
    note(cx, "exit Backoff");
}

fn entry_connected<S: Sink<Command>>(_up: ConnectedFields<'_>, cx: &mut ConnCx<'_, S>) {
    note(cx, "entry Connected");
}

/// Whatever the way out, the transport session is closed.
fn exit_connected<S: Sink<Command>>(up: ConnectedFields<'_>, cx: &mut ConnCx<'_, S>) {
    note(cx, "exit Connected");
    emit(
        cx,
        Command::Close {
            session: up.session.id,
        },
    );
}

fn entry_idle<S: Sink<Command>>(cx: &mut ConnCx<'_, S>) {
    note(cx, "entry Idle");
}

fn exit_idle<S: Sink<Command>>(cx: &mut ConnCx<'_, S>) {
    note(cx, "exit Idle");
}

fn entry_sending<S: Sink<Command>>(_sending: SendingMut<'_>, cx: &mut ConnCx<'_, S>) {
    note(cx, "entry Sending");
}

fn exit_sending<S: Sink<Command>>(_sending: SendingMut<'_>, cx: &mut ConnCx<'_, S>) {
    note(cx, "exit Sending");
}

fn entry_pinging<S: Sink<Command>>(cx: &mut ConnCx<'_, S>) {
    note(cx, "entry Pinging");
}

fn exit_pinging<S: Sink<Command>>(cx: &mut ConnCx<'_, S>) {
    note(cx, "exit Pinging");
}

/// The ping goes out when the state is entered; the timer waits for the pong.
fn entry_awaiting_pong<S: Sink<Command>>(cx: &mut ConnCx<'_, S>) {
    note(cx, "entry AwaitingPong");
    emit(cx, Command::Ping);
}

fn exit_awaiting_pong<S: Sink<Command>>(cx: &mut ConnCx<'_, S>) {
    note(cx, "exit AwaitingPong");
}

/// `Dead` lives for one microstep: its entry raises the event its own
/// handler answers by leaving `Connected` (spec 5.3: entries cannot
/// transition, they may `raise`).
fn entry_dead<S: Sink<Command>>(cx: &mut ConnCx<'_, S>) {
    note(cx, "entry Dead");
    cx.raise(Event::KeepaliveDead);
}

fn exit_dead<S: Sink<Command>>(cx: &mut ConnCx<'_, S>) {
    note(cx, "exit Dead");
}

// Composites generated by the macro.

/// Entry of the leaf of the `link` region.
pub fn enter_link<S: Sink<Command>>(link: &mut Link, cx: &mut ConnCx<'_, S>) {
    match link {
        Link::Idle => entry_idle(cx),
        Link::Sending { frame } => entry_sending(SendingMut { frame }, cx),
    }
}

/// Exit of the leaf of the `link` region.
pub fn exit_link<S: Sink<Command>>(link: &mut Link, cx: &mut ConnCx<'_, S>) {
    match link {
        Link::Idle => exit_idle(cx),
        Link::Sending { frame } => exit_sending(SendingMut { frame }, cx),
    }
}

/// Entry of the leaf of the `keepalive` region.
pub fn enter_keepalive<S: Sink<Command>>(keepalive: Keepalive, cx: &mut ConnCx<'_, S>) {
    match keepalive {
        Keepalive::Pinging => entry_pinging(cx),
        Keepalive::AwaitingPong => entry_awaiting_pong(cx),
        Keepalive::Dead => entry_dead(cx),
    }
}

/// Exit of the leaf of the `keepalive` region.
pub fn exit_keepalive<S: Sink<Command>>(keepalive: Keepalive, cx: &mut ConnCx<'_, S>) {
    match keepalive {
        Keepalive::Pinging => exit_pinging(cx),
        Keepalive::AwaitingPong => exit_awaiting_pong(cx),
        Keepalive::Dead => exit_dead(cx),
    }
}

/// Entries of the whole active configuration (step 7), then epochs and
/// scheduling (steps 8 and 9).
pub fn enter_root<S: Sink<Command>>(root: &mut Conn, cx: &mut ConnCx<'_, S>) {
    match root {
        Conn::Disconnected => entry_disconnected(cx),
        Conn::Connecting { attempt } => entry_connecting(ConnectingMut { attempt }, cx),
        Conn::Backoff { attempt } => entry_backoff(BackoffMut { attempt }, cx),
        Conn::Connected(connected) => {
            let keepalive = connected.keepalive;
            let (up, link, _) = connected.split();
            entry_connected(up, cx);
            enter_link(link, cx);
            enter_keepalive(keepalive, cx);
        }
    }
    start_root(root, cx);
}

/// Exits of the whole active configuration (step 1), then the cancellations
/// of their timers and invokes (step 2).
pub fn exit_root<S: Sink<Command>>(root: &mut Conn, cx: &mut ConnCx<'_, S>) {
    match root {
        Conn::Disconnected => exit_disconnected(cx),
        Conn::Connecting { attempt } => exit_connecting(ConnectingMut { attempt }, cx),
        Conn::Backoff { attempt } => exit_backoff(BackoffMut { attempt }, cx),
        Conn::Connected(connected) => {
            let keepalive = connected.keepalive;
            let (up, link, _) = connected.split();
            exit_keepalive(keepalive, cx);
            exit_link(link, cx);
            exit_connected(up, cx);
        }
    }
    cancel_root(root, cx);
}
