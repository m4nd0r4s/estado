/// Entries of the whole active configuration (step 7), then epochs and
/// scheduling (steps 8 and 9).
pub fn enter_root<S: Sink<Command>>(root: &mut Character, cx: &mut CharacterCx<'_, S>) {
    match root {
        Character::Alive(alive) => {
            let (movement, weapon, anim) = (alive.movement, alive.weapon, alive.anim);
            entry_alive(alive.split().0, cx);
            enter_movement(movement, cx);
            enter_weapon(weapon, cx);
            enter_anim(anim, cx);
        }
        Character::Dead => entry_dead(cx),
    }
    start_root(root, cx);
}

/// Exits of the whole active configuration (step 1), then the cancellations
/// of their timers (step 2).
pub fn exit_root<S: Sink<Command>>(root: &mut Character, cx: &mut CharacterCx<'_, S>) {
    match root {
        Character::Alive(alive) => {
            let (movement, weapon, anim) = (alive.movement, alive.weapon, alive.anim);
            exit_anim(anim, cx);
            exit_weapon(weapon, cx);
            exit_movement(movement, cx);
            exit_alive(alive.split().0, cx);
        }
        Character::Dead => exit_dead(cx),
    }
    cancel_root(root, cx);
}
