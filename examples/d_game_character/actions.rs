//! Entries and exits, as generated linear code (spec 5.3 steps 1, 7).
//!
//! The user writes the per-state functions (`entry_*`, `exit_*`); the macro
//! writes the composites that walk the hierarchy: on exit the regions go in
//! reverse declaration order (`anim`, `weapon`, `movement`) and the parallel
//! state last; on entry the parallel state comes first, then the regions in
//! declaration order. Every action notes itself in the global context, so
//! tests can assert the exact order of entries, exits and handlers.

use estado_core::{Cx, Sink};

use super::model::{Anim, Character, Command, Movement, Sound, Weapon};
use super::tasks::{cancel_root, start_root};
use super::views::AliveFields;

/// The `Cx` of this machine.
pub type CharacterCx<'step, S> = Cx<'step, Character, S>;

/// Appends a line to the trace kept in the global context.
#[inline]
pub fn note<S: Sink<Command>>(cx: &mut CharacterCx<'_, S>, line: &'static str) {
    cx.ctx_mut().note(line);
}

