//! Entries and exits, as generated linear code (spec 5.3 steps 1 and 7).
//!
//! The user writes the per-state functions (`entry_*`, `exit_*`); the macro
//! writes the composites that walk the hierarchy. Every action logs a line in
//! the global context, so tests can assert the exact order of entries, exits,
//! handlers and effects; `emit` logs before it forwards to `cx.emit`.

use estado_core::{Cx, Sink};

use super::model::{ActiveSub, Command, Player};
use super::views::{ActiveFields, FailedMut, PausedMut, PlayingMut};

pub type PlayerCx<'step, S> = Cx<'step, Player, S>;

/// Appends a line to the trace kept in the global context.
pub fn note<S: Sink<Command>>(cx: &mut PlayerCx<'_, S>, line: &str) {
    cx.ctx_mut().push(line.to_owned());
}

/// Traces and emits a command.
pub fn emit<S: Sink<Command>>(cx: &mut PlayerCx<'_, S>, command: Command) {
    let line = format!("emit {command:?}");
    cx.ctx_mut().push(line);
    cx.emit(command);
}

// Entries and exits written by the user, one per state.

fn entry_idle<S: Sink<Command>>(cx: &mut PlayerCx<'_, S>) {
    note(cx, "entry Idle");
}

fn exit_idle<S: Sink<Command>>(cx: &mut PlayerCx<'_, S>) {
    note(cx, "exit Idle");
}

fn entry_active<S: Sink<Command>>(up: ActiveFields<'_>, cx: &mut PlayerCx<'_, S>) {
    note(cx, "entry Active");
    emit(cx, Command::OpenTrack(*up.track));
}

fn exit_active<S: Sink<Command>>(up: ActiveFields<'_>, cx: &mut PlayerCx<'_, S>) {
    note(cx, "exit Active");
    emit(cx, Command::CloseTrack(*up.track));
}

fn entry_playing<S: Sink<Command>>(_playing: PlayingMut<'_>, cx: &mut PlayerCx<'_, S>) {
    note(cx, "entry Playing");
    emit(cx, Command::StartOutput);
}

fn exit_playing<S: Sink<Command>>(_playing: PlayingMut<'_>, cx: &mut PlayerCx<'_, S>) {
    note(cx, "exit Playing");
    emit(cx, Command::StopOutput);
}

fn entry_paused<S: Sink<Command>>(_paused: PausedMut<'_>, cx: &mut PlayerCx<'_, S>) {
    note(cx, "entry Paused");
}

fn exit_paused<S: Sink<Command>>(_paused: PausedMut<'_>, cx: &mut PlayerCx<'_, S>) {
    note(cx, "exit Paused");
}

fn entry_failed<S: Sink<Command>>(failed: FailedMut<'_>, cx: &mut PlayerCx<'_, S>) {
    note(cx, "entry Failed");
    emit(cx, Command::ShowError(failed.reason.clone()));
}

pub fn exit_failed<S: Sink<Command>>(_failed: FailedMut<'_>, cx: &mut PlayerCx<'_, S>) {
    note(cx, "exit Failed");
}

// Composites generated by the macro: the deepest state exits first (step 1),
// the shallowest enters first (step 7).

pub fn enter_active_sub<S: Sink<Command>>(sub: &mut ActiveSub, cx: &mut PlayerCx<'_, S>) {
    match sub {
        ActiveSub::Playing { pos } => entry_playing(PlayingMut { pos }, cx),
        ActiveSub::Paused { pos } => entry_paused(PausedMut { pos }, cx),
    }
}

pub fn exit_active_sub<S: Sink<Command>>(sub: &mut ActiveSub, cx: &mut PlayerCx<'_, S>) {
    match sub {
        ActiveSub::Playing { pos } => exit_playing(PlayingMut { pos }, cx),
        ActiveSub::Paused { pos } => exit_paused(PausedMut { pos }, cx),
    }
}

pub fn enter_root_state<S: Sink<Command>>(state: &mut Player, cx: &mut PlayerCx<'_, S>) {
    match state {
        Player::Idle => entry_idle(cx),
        Player::Active(active) => {
            let (up, sub) = active.split();
            entry_active(up, cx);
            enter_active_sub(sub, cx);
        }
        Player::Failed { reason, buffer } => entry_failed(FailedMut { reason, buffer }, cx),
    }
}

pub fn exit_root_state<S: Sink<Command>>(state: &mut Player, cx: &mut PlayerCx<'_, S>) {
    match state {
        Player::Idle => exit_idle(cx),
        Player::Active(active) => {
            let (up, sub) = active.split();
            exit_active_sub(sub, cx);
            exit_active(up, cx);
        }
        Player::Failed { reason, buffer } => exit_failed(FailedMut { reason, buffer }, cx),
    }
}
