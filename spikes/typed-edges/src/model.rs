//! The media player of spec 3.2, as the user would declare it.

#[derive(Debug, PartialEq)]
pub enum Player {
    Idle,
    Active(Active),
    Failed { reason: String, buffer: Vec<u8> },
}

/// Compound state: shared data plus the substate enum.
#[derive(Debug, PartialEq)]
pub struct Active {
    pub track: u32,
    /// Not `Clone` on purpose in the real scenario: it must be moved.
    pub buffer: Vec<u8>,
    pub sub: ActiveSub,
}

#[derive(Debug, PartialEq)]
pub enum ActiveSub {
    Playing { position: u32 },
    Paused { position: u32 },
}

pub enum Event {
    Play(u32),
    Pause,
    Resume,
    Tick,
    Error(String),
    /// Payload parsed with `?` inside a handler.
    Seek(&'static str),
    /// Exercises a `goto!` inside a closure.
    MaybeStop(Option<u32>),
}

/// View generated by the macro for `#[on(Playing)]` handlers: every field of
/// `Active` except `#[substates]`, borrowed mutably (split borrow, spec 6.2).
pub struct ActiveFields<'state> {
    pub track: &'state mut u32,
    pub buffer: &'state mut Vec<u8>,
}

#[derive(Debug, PartialEq)]
pub struct SeekError;

impl From<core::num::ParseIntError> for SeekError {
    fn from(_: core::num::ParseIntError) -> Self {
        SeekError
    }
}
